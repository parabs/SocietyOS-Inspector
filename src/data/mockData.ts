// Generate additional simulated transactions across all 12 months to realistically reach the 1,478 total transactions
// so pagination, filtering, searching and table behavior match real production scale.
export function generateFullTransactions(): EnrichedTransaction[] {
  const result: EnrichedTransaction[] = [...INITIAL_TRANSACTIONS];
  const months = [
    'Apr 2018', 'May 2018', 'Jun 2018', 'Jul 2018', 'Aug 2018', 'Sep 2018',
    'Oct 2018', 'Nov 2018', 'Dec 2018', 'Jan 2019', 'Feb 2019', 'Mar 2019'
  ];
  const accounts: ('TDCC' | 'BOM' | 'CASH')[] = ['TDCC', 'BOM', 'CASH'];
  const parties = [
    'Flat A-101 Maintenance', 'Flat A-102 Maintenance', 'Flat B-201 Maintenance',
    'Flat B-202 Maintenance', 'Flat C-301 Maintenance', 'Flat C-302 Maintenance',
    'ABC Water Suppliers', 'Electricity Board MSEDCL', 'Security Agency Guards',
    'Lift Maintenance Co.', 'Cleaning Services Contractor', 'Pest Control Services',
    'Rakesh Electricals', 'S.K. Plumbing Works', 'Stationery Mart', 'Audit Fees'
  ];

  let currentId = 100;
  // Let's create transactions up to 1478 total
  for (let i = result.length; i < 1478; i++) {
    const month = months[i % 12];
    const account = accounts[i % 3];
    const isPayment = (i % 2 === 0);
    const party = parties[i % parties.length];
    const amount = isPayment ? (1000 + (i * 137) % 25000) : (4500 + (i * 95) % 12000);
    const day = (1 + (i % 28)).toString().padStart(2, '0');
    const monthNum = ((i % 12) + 4 > 12 ? (i % 12) + 4 - 12 : (i % 12) + 4).toString().padStart(2, '0');
    const year = (i % 12) >= 9 ? '2019' : '2018';
    
    // Distribution matching the design:
    // Total: 1,478 | Inspected: 352 (Complete: 302, Discrepancy: 38, Missing: 12)
    // Pending: 1,126 | Audit Failed: 20
    const isInspected = i < 352;
    let billStatus: 'Available' | 'Discrepancy' | 'Missing' | 'N/A' = 'Available';
    let voucherReceiptStatus: 'Available' | 'Discrepancy' | 'Missing' = 'Available';
    let evidenceStatus: 'Complete' | 'Discrepancy' | 'Missing' | 'Pending' | 'N/A' = 'Pending';
    let internalAuditStatus: 'Pending' | 'Verified' | 'Failed' = 'Pending';
    let remarks = '-';

    if (isInspected) {
      if (i >= 302 && i < 340) {
        // 38 Discrepancies
        billStatus = 'Discrepancy';
        voucherReceiptStatus = 'Available';
        evidenceStatus = 'Discrepancy';
        remarks = 'Amount mismatch on inspection';
      } else if (i >= 340 && i < 352) {
        // 12 Missing
        billStatus = 'Missing';
        voucherReceiptStatus = 'Missing';
        evidenceStatus = 'Missing';
        remarks = 'Supporting document missing';
      } else {
        // Complete
        billStatus = !isPayment ? 'N/A' : 'Available';
        voucherReceiptStatus = 'Available';
        evidenceStatus = 'Complete';
        internalAuditStatus = (i < 282) ? 'Verified' : 'Pending';
      }

      if (i >= 332 && i < 352) {
        // 20 Audit Failed
        internalAuditStatus = 'Failed';
        remarks = remarks === '-' ? 'Failed internal audit compliance test' : remarks + '; audit failed';
      }
    }

    result.push({
      id: `TXN-2018-${currentId.toString().padStart(5, '0')}`,
      sourceFile: 'Varsha_Nivas_Accounts_2018-19.xlsx',
      sourceSheet: `${account}_${month.replace(' ', '_')}`,
      sourceRow: 10 + (i % 80),
      date: `${year}-${monthNum}-${day}`,
      month,
      accountId: account,
      type: isPayment ? 'Payment' : 'Receipt',
      party,
      description: isPayment ? `${party} monthly charge` : `Quarterly maintenance receipt`,
      amount,
      voucherNo: isPayment ? `V-${100 + (i % 900)}` : undefined,
      receiptNo: !isPayment ? `R-${(i % 500).toString().padStart(3, '0')}` : undefined,
      billStatus,
      voucherReceiptStatus,
      evidenceStatus,
      internalAuditStatus,
      remarks,
      reviewer: isInspected ? 'Sachin Parab' : undefined,
      updatedAt: isInspected ? '2026-10-20T12:00:00Z' : undefined,
    });
    currentId++;
  }
  return result;
}

