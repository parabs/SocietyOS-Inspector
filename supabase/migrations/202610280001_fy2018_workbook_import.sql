-- FY 2018-19 workbook import audit tables and tightly scoped admin-only browser access.
-- Assign app_metadata.role = "society_admin" (or app_metadata.roles containing "society_admin")
-- to approved Supabase Auth users. Do not use user_metadata for authorization.

CREATE TABLE IF NOT EXISTS public.society_import_batches (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  source_file text NOT NULL,
  financial_year text NOT NULL,
  status text NOT NULL DEFAULT 'Started',
  row_counts jsonb NOT NULL DEFAULT '{}'::jsonb,
  error_summary text,
  started_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  created_by uuid DEFAULT auth.uid()
);

CREATE TABLE IF NOT EXISTS public.society_correction_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  financial_year text NOT NULL,
  rule_item text NOT NULL,
  correction_applied text NOT NULL,
  scope_note text,
  import_batch_id uuid REFERENCES public.society_import_batches(id),
  imported_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT society_correction_log_natural_key
    UNIQUE (financial_year, rule_item, correction_applied, scope_note)
);

CREATE TABLE IF NOT EXISTS public.party_category_rules (
  rule_id text PRIMARY KEY,
  rule_area text,
  rule_text text NOT NULL,
  implementation_example text,
  review_exception text,
  import_batch_id uuid REFERENCES public.society_import_batches(id),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.society_dropdown_options (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  column_name text NOT NULL,
  option_value text NOT NULL,
  description text,
  import_batch_id uuid REFERENCES public.society_import_batches(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT society_dropdown_options_natural_key UNIQUE (column_name, option_value)
);

CREATE OR REPLACE FUNCTION public.is_society_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public
AS $$
  SELECT
    coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') = 'society_admin'
    OR coalesce(auth.jwt() -> 'app_metadata' -> 'roles', '[]'::jsonb) ? 'society_admin';
$$;

GRANT EXECUTE ON FUNCTION public.is_society_admin() TO authenticated;

DO $$
DECLARE
  target_table text;
  target_tables text[] := ARRAY[
    'source_register', 'flat_owner_master', 'account_master', 'category_master',
    'party_master', 'rules_master', 'transactions', 'demand_register',
    'member_opening_balances', 'society_import_batches',
    'society_correction_log', 'party_category_rules', 'society_dropdown_options'
  ];
  policy_name text := 'society_os_admin_all';
BEGIN
  FOREACH target_table IN ARRAY target_tables LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', target_table);
    IF NOT EXISTS (
      SELECT 1 FROM pg_policies
      WHERE schemaname = 'public'
        AND tablename = target_table
        AND policyname = policy_name
    ) THEN
      EXECUTE format(
        'CREATE POLICY %I ON public.%I FOR ALL TO authenticated USING (public.is_society_admin()) WITH CHECK (public.is_society_admin())',
        policy_name, target_table
      );
    END IF;
  END LOOP;
END $$;

ALTER TABLE public."OPTIONS" ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'OPTIONS' AND policyname = 'society_os_admin_all'
  ) THEN
    CREATE POLICY society_os_admin_all ON public."OPTIONS"
      FOR ALL TO authenticated
      USING (public.is_society_admin())
      WITH CHECK (public.is_society_admin());
  END IF;
END $$;

COMMENT ON TABLE public.society_import_batches IS 'Audit trail for explicit Society OS workbook imports.';
COMMENT ON TABLE public.society_correction_log IS 'Imported financial data correction log; source workbook remains the authoritative evidence.';
COMMENT ON TABLE public.party_category_rules IS 'Persistent party and category mapping rules imported from the approved workbook.';
COMMENT ON TABLE public.society_dropdown_options IS 'Controlled dropdown values imported from the workbook; separate from the existing OPTIONS application-configuration table.';
COMMENT ON COLUMN public.transactions.cheque_no IS 'Cheque number/reference from source workbook; stored as text to preserve leading zeroes.';
COMMENT ON COLUMN public.transactions.bank_verified IS 'Bank statement reconciliation status; separate from voucher/document verification.';
